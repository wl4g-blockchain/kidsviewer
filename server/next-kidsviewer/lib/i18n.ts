// 从localStorage获取语言设置，如果没有则默认为'en'
const getStoredLanguage = () => {
    if (typeof window !== 'undefined') {
        return localStorage.getItem('kidsviewer-language') || 'en'
    }
    return 'en'
}

i18n
    .use(initReactI18next)
    .init({
        resources,
        lng: getStoredLanguage(),
        fallbackLng: 'en',
        interpolation: {
            escapeValue: false,
        },
    })

// 监听语言变化并保存到localStorage
i18n.on('languageChanged', (lng) => {
    if (typeof window !== 'undefined') {
        localStorage.setItem('kidsviewer-language', lng)
    }
})

export default i18n
